/**
 * Host-config install helpers for pulsechain-mcp (agent-safe).
 *
 * Modes:
 *   research — dist/index.js, AGENT_WALLET_ENABLED=false, no secrets
 *   wallets  — scripts/start-wallet-mcp.mjs, secrets only in .env.wallet
 *
 * Never embeds AGENT_WALLET_MASTER_KEY in host config. Never prints secrets.
 */
import { existsSync, mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import {
  createWalletEnvWriteOnly,
  tryRestrictiveDirMode,
  looksLikeMasterKeyHex,
} from "./wallet-env.mjs";

export const HOSTS = ["grok", "cursor", "claude", "codex"];
export const MODES = ["research", "wallets"];

const COMMON_RPC =
  "https://rpc-pulsechain.g4mm4.io,https://rpc.pulsechain.com,https://pulsechain.publicnode.com,https://rpc.pulsechainstats.com";
const EXPLORER = "https://api.scan.pulsechain.com/api";
const SUB_V1 = "https://graph.pulsechain.com/subgraphs/name/pulsechain/pulsex";
const SUB_V2 = "https://graph.pulsechain.com/subgraphs/name/pulsechain/pulsexv2";

/**
 * Resolve clone-root absolute paths used in host configs.
 * @param {string} cloneRoot
 * @param {"research"|"wallets"} mode
 */
export function resolveInstallPaths(cloneRoot, mode) {
  const root = resolve(cloneRoot);
  const distEntry = join(root, "dist", "index.js");
  const launcher = join(root, "scripts", "start-wallet-mcp.mjs");
  const walletDir = join(root, "data", "wallets");
  const envWallet = join(root, ".env.wallet");
  // Prefer forward slashes in generated configs (Windows-friendly for Node)
  const slash = (p) => p.replace(/\\/g, "/");
  return {
    root,
    distEntry,
    launcher,
    walletDir,
    envWallet,
    entryArg: slash(mode === "wallets" ? launcher : distEntry),
    walletDirSlash: slash(walletDir),
    rootSlash: slash(root),
  };
}

/**
 * Build host config text (no secrets).
 * @param {{ host: string, mode: "research"|"wallets", paths: ReturnType<typeof resolveInstallPaths> }} opts
 */
export function buildHostConfigText(opts) {
  const { host, mode, paths } = opts;
  const entry = paths.entryArg;
  const walletsEnabled = mode === "wallets";

  if (host === "cursor" || host === "claude") {
    const env = {
      PULSECHAIN_RPC_URLS: COMMON_RPC,
      PULSECHAIN_EXPLORER_API: EXPLORER,
      PULSEX_SUBGRAPH_V1: SUB_V1,
      PULSEX_SUBGRAPH_V2: SUB_V2,
      HTTP_TIMEOUT_MS: "30000",
      AGENT_WALLET_ENABLED: walletsEnabled ? "true" : "false",
      LOG_LEVEL: "info",
    };
    // Research: no master key, optional wallet dir omitted.
    // Wallets: launcher loads .env.wallet — do not put master key here.
    // Keep AGENT_WALLET_DIR only as documentation of unique dir when research uses dist.
    if (!walletsEnabled) {
      // research-only sample shape
    } else {
      // Launcher owns dir; still harmless to omit AGENT_WALLET_DIR from host.
    }
    const json = {
      mcpServers: {
        "pulsechain-mcp": {
          command: "node",
          args: [entry],
          env,
        },
      },
    };
    return JSON.stringify(json, null, 2) + "\n";
  }

  // grok / codex TOML
  const lines = [
    `# pulsechain-mcp — ${mode} mode (generated by scripts/install-for-host.mjs)`,
    `# Clone root: ${paths.rootSlash}`,
    `# Secrets: ${walletsEnabled ? "gitignored .env.wallet only (never in this file)" : "none (research-only)"}`,
    `# Do NOT set HTTP_TRANSPORT_PORT for stdio hosts.`,
    "",
    "[mcp_servers.pulsechain-mcp]",
    'command = "node"',
    `args = ["${entry}"]`,
    "enabled = true",
    "startup_timeout_sec = 45",
    "tool_timeout_sec = 120",
    "",
    "[mcp_servers.pulsechain-mcp.env]",
    `PULSECHAIN_RPC_URLS = "${COMMON_RPC}"`,
    `PULSECHAIN_EXPLORER_API = "${EXPLORER}"`,
    `PULSEX_SUBGRAPH_V1 = "${SUB_V1}"`,
    `PULSEX_SUBGRAPH_V2 = "${SUB_V2}"`,
    'HTTP_TIMEOUT_MS = "30000"',
    `AGENT_WALLET_ENABLED = "${walletsEnabled ? "true" : "false"}"`,
    'LOG_LEVEL = "info"',
    "",
  ];
  return lines.join("\n");
}

/**
 * Default output path for a generated host sample (under clone).
 * @param {string} cloneRoot
 * @param {string} host
 * @param {"research"|"wallets"} mode
 */
export function defaultHostOutputPath(cloneRoot, host, mode) {
  const base = resolve(cloneRoot, "data", "install-host-configs");
  const ext = host === "cursor" || host === "claude" ? "json" : "toml";
  return join(base, `${host}-${mode}.${ext}`);
}

/**
 * Suggested host destinations (printed only — installer does not write into ~/.grok by default).
 */
export function suggestedHostDestinations(host) {
  switch (host) {
    case "grok":
      return [
        "~/.grok/config.toml (user)",
        "project .grok/config.toml",
      ];
    case "cursor":
      return [
        "project .cursor/mcp.json",
        "Cursor MCP settings UI",
      ];
    case "claude":
      return ["Claude Desktop claude_desktop_config.json"];
    case "codex":
      return [
        "~/.codex/config.toml (user)",
        "project .codex/config.toml (trusted only)",
      ];
    default:
      return [];
  }
}

/**
 * Run install-for-host logic.
 *
 * @param {{
 *   cloneRoot: string,
 *   host: string,
 *   mode: "research"|"wallets",
 *   outPath?: string | null,
 *   writeHostConfig?: boolean,
 *   createKeyIfMissing?: boolean,
 * }} opts
 */
export function installForHost(opts) {
  const messages = [];
  const host = String(opts.host || "").toLowerCase();
  const mode = String(opts.mode || "").toLowerCase();

  if (!HOSTS.includes(host)) {
    return {
      ok: false,
      code: "BAD_HOST",
      error: `Unknown host "${opts.host}". Use: ${HOSTS.join("|")}`,
      messages: [`Unknown host. Supported: ${HOSTS.join(", ")}`],
    };
  }
  if (!MODES.includes(mode)) {
    return {
      ok: false,
      code: "BAD_MODE",
      error: `Unknown mode "${opts.mode}". Use: research|wallets`,
      messages: [`Unknown mode. Supported: ${MODES.join(", ")}`],
    };
  }

  const cloneRoot = resolve(opts.cloneRoot);
  const paths = resolveInstallPaths(cloneRoot, mode);
  const writeHost = opts.writeHostConfig !== false;
  const createKey = opts.createKeyIfMissing !== false;

  if (!existsSync(paths.distEntry) && mode === "research") {
    messages.push(
      `Note: dist/index.js not found yet at ${paths.distEntry} — run npm run build before host reload.`,
    );
  }
  if (mode === "wallets" && !existsSync(paths.launcher)) {
    return {
      ok: false,
      code: "NO_LAUNCHER",
      error: "scripts/start-wallet-mcp.mjs missing",
      messages: ["Launcher script missing — is this a full clone of pulsechain-mcp?"],
    };
  }

  let walletResult = null;
  if (mode === "wallets") {
    if (existsSync(paths.envWallet)) {
      messages.push(
        ".env.wallet already present — leaving it untouched (no overwrite).",
      );
      messages.push(
        "Verify with existence check only; never read_file the key contents.",
      );
      walletResult = {
        ok: true,
        created: false,
        envPath: paths.envWallet,
        code: "ENV_EXISTS_OK",
      };
    } else if (createKey) {
      walletResult = createWalletEnvWriteOnly({ cloneRoot });
      messages.push(...walletResult.messages);
      if (!walletResult.ok && walletResult.code !== "ENV_EXISTS") {
        return {
          ok: false,
          code: walletResult.code,
          error: walletResult.error,
          messages,
          walletResult,
        };
      }
    } else {
      messages.push(
        ".env.wallet missing. Run: node scripts/install-for-host.mjs --host " +
          host +
          " --mode wallets",
      );
      messages.push(
        "Or: node scripts/generate-wallet-env.mjs  (write-only; never prints the key)",
      );
      return {
        ok: false,
        code: "ENV_MISSING",
        error: ".env.wallet missing",
        messages,
      };
    }
    const dirMode = tryRestrictiveDirMode(paths.walletDir, 0o700);
    if (dirMode.note) messages.push(dirMode.note);
  }

  const configText = buildHostConfigText({ host, mode, paths });

  // Safety: generated host config must never contain a 64-hex key
  if (looksLikeMasterKeyHex(configText)) {
    throw new Error("internal: host config must not contain master-key-shaped secrets");
  }
  if (/AGENT_WALLET_MASTER_KEY\s*[=:]/.test(configText)) {
    throw new Error("internal: host config must not assign AGENT_WALLET_MASTER_KEY");
  }

  let outPath = opts.outPath
    ? resolve(opts.outPath)
    : defaultHostOutputPath(cloneRoot, host, mode);

  if (writeHost) {
    mkdirSync(dirname(outPath), { recursive: true });
    writeFileSync(outPath, configText, "utf8");
    messages.push(`Wrote host sample (no secrets): ${outPath}`);
  }

  messages.push("");
  messages.push("=== Next steps (no secrets printed) ===");
  messages.push(
    `1. Merge the generated ${host} ${mode} block into your host config:`,
  );
  for (const d of suggestedHostDestinations(host)) {
    messages.push(`   - ${d}`);
  }
  messages.push(
    "2. Pre-reload: host-native doctor only (e.g. grok mcp doctor pulsechain-mcp).",
  );
  messages.push(
    "   Doctor proves process/handshake — it does NOT inject tools into this chat.",
  );
  messages.push("3. Reload / restart the MCP host (new session or turn).");
  messages.push(
    "4. Post-reload smoke: pulsechain_health → agent_wallet_status → optional get_rpc_health.",
  );
  messages.push(
    "5. Version: match package.json / npm pkg get version (do not hardcode).",
  );
  if (mode === "research") {
    messages.push(
      "Research-only: AGENT_WALLET_ENABLED=false; promote to wallets-on only when user asks to sign.",
    );
  } else {
    messages.push(
      "Wallets-on: host points at start-wallet-mcp.mjs; key stays in gitignored .env.wallet only.",
    );
    messages.push(
      "Do NOT fund during bootstrap. Do NOT paste or console.log the master key.",
    );
  }

  // Final belt: no key-shaped strings in any message
  for (const m of messages) {
    if (looksLikeMasterKeyHex(m)) {
      throw new Error("internal: install messages must not contain master-key-shaped text");
    }
  }

  return {
    ok: true,
    host,
    mode,
    paths,
    outPath: writeHost ? outPath : null,
    configText,
    walletResult,
    messages,
  };
}

/**
 * Parse CLI argv for install-for-host.
 * @param {string[]} argv
 */
export function parseInstallArgs(argv) {
  const out = {
    host: null,
    mode: null,
    cloneRoot: null,
    outPath: null,
    help: false,
    noWrite: false,
    noKey: false,
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--help" || a === "-h") out.help = true;
    else if (a === "--host") out.host = argv[++i];
    else if (a === "--mode") out.mode = argv[++i];
    else if (a === "--clone-root") out.cloneRoot = argv[++i];
    else if (a === "--out") out.outPath = argv[++i];
    else if (a === "--no-write") out.noWrite = true;
    else if (a === "--no-key") out.noKey = true;
  }
  return out;
}

export function installHelpText() {
  return `Usage: node scripts/install-for-host.mjs --host <grok|cursor|claude|codex> --mode <research|wallets> [options]

Agent-safe installer for pulsechain-mcp.

  --host          Target MCP host
  --mode          research (default agent path) | wallets (signing; launcher + .env.wallet)
  --clone-root    Clone root (default: cwd)
  --out           Where to write generated host sample (default: data/install-host-configs/<host>-<mode>.*)
  --no-write      Print next steps only; do not write host sample file
  --no-key        Wallets mode: do not create .env.wallet (fail if missing)

Never prints secrets. Never embeds AGENT_WALLET_MASTER_KEY in host config.
Idempotent: re-run leaves existing .env.wallet untouched (refuse overwrite).
`;
}
